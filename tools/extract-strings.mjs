// Inventory Chinese strings in the bundle so they can be rewritten in place.
// Usage: node tools/extract-strings.mjs [dir=bundle]
// Output: docs/i18n-inventory.md
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, extname } from "node:path";

const ROOT = process.argv[2] || "bundle";
const EXTS = new Set([".js", ".html", ".css"]);
const CJK = /[\u4e00-\u9fa5]/;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === "vendor" || name === "node_modules") continue;
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (EXTS.has(extname(name))) out.push(p);
  }
  return out;
}

// Pull quoted segments that contain CJK; fall back to the whole trimmed line (HTML text).
function segments(line) {
  const quoted = [...line.matchAll(/(['"`])((?:\\.|(?!\1)[^\\])*)\1/g)]
    .map((m) => m[2])
    .filter((s) => CJK.test(s));
  return quoted.length ? quoted : (CJK.test(line) ? [line.trim()] : []);
}

const files = walk(ROOT).sort();
const rows = [];
const perFile = [];

for (const file of files) {
  const rel = relative(ROOT, file).replace(/\\/g, "/");
  const lines = readFileSync(file, "utf8").split(/\r?\n/);
  let comment = 0;
  let short = 0;
  let long = 0;

  lines.forEach((line, i) => {
    if (!CJK.test(line)) return;
    const trimmed = line.trim();
    if (trimmed.startsWith("//") || trimmed.startsWith("*") || trimmed.startsWith("/*")) {
      comment++;
      return;
    }
    for (const text of segments(line)) {
      const kind = text.length <= 40 && !text.includes("\n") ? "short" : "long";
      kind === "short" ? short++ : long++;
      rows.push({ rel, line: i + 1, kind, text });
    }
  });

  if (comment + short + long > 0) perFile.push({ rel, comment, short, long });
}

const sum = (k) => perFile.reduce((n, f) => n + f[k], 0);
const shortRows = rows.filter((r) => r.kind === "short");
const longRows = rows.filter((r) => r.kind === "long");

const esc = (s) => s.replace(/\|/g, "\\|").replace(/`/g, "\u0060");

let md = `# i18n inventory

Generated by \`node tools/extract-strings.mjs\`. Re-run after edits; do not hand-edit.

- files with Chinese: **${perFile.length}**
- short labels (<= 40 chars, rewrite in place): **${sum("short")}**
- long text (prompts / templates / examples, must be rewritten by hand): **${sum("long")}**
- comments and logs (not user-visible, delete or translate as you touch them): **${sum("comment")}**

## Per file

| file | short | long | comment |
|---|--:|--:|--:|
`;
for (const f of perFile.sort((a, b) => b.short + b.long - (a.short + a.long))) {
  md += `| \`${f.rel}\` | ${f.short} | ${f.long} | ${f.comment} |\n`;
}

md += `\n## Short labels (${shortRows.length})\n\n| file:line | text |\n|---|---|\n`;
for (const r of shortRows) md += `| \`${r.rel}:${r.line}\` | ${esc(r.text)} |\n`;

md += `\n## Long text (${longRows.length}) — rewrite by hand\n\n| file:line | chars | text |\n|---|--:|---|\n`;
for (const r of longRows) md += `| \`${r.rel}:${r.line}\` | ${r.text.length} | ${esc(r.text)} |\n`;

mkdirSync("docs", { recursive: true });
writeFileSync("docs/i18n-inventory.md", md);
console.log(
  `files=${perFile.length} short=${sum("short")} long=${sum("long")} comment=${sum("comment")} -> docs/i18n-inventory.md`
);
